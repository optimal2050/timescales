#' Pre-built calendars from the catalog
#'
#' A named list holding every calendar in [`calendar_catalog()`],
#' pre-constructed — `calendars$d365_h24` is identical to
#' `calendar("d365_h24")`. Ported from the predecessor `timeslices` package's
#' calendar library, with one deliberate difference: shares here are
#' **duration-proportional** (January is `31/365` of the year, not `1/12`),
#' where timeslices shipped uniform shares.
#'
#' @format A named list of 37 [`Calendar`] objects. Names are the catalog
#'   ids (`d365`, `d365_h24`, `m12`, `m12_h24`, `m12_md365`, `q4_h24`,
#'   `s4_hp3`, ...); see [`calendar_catalog()`] for the full table with
#'   timeslice counts, coverage, and regularity.
#'
#' @source Generated by `data-raw/calendars.R` from the package's own
#'   catalog (`calendar(id)` for each id).
#'
#' @examples
#' names(calendars)
#' calendars$m12
#' identical(
#'   S7::prop(calendars$q4, "leaves"),
#'   S7::prop(calendar("q4"), "leaves")
#' )
"calendars"

